"""Ночной свет: данные Windows (Bond CompactBinary) — примеры из win-nightlight-cli."""
import pytest

from capri import nightlight as N

OFF = bytes([0x43, 0x42, 0x01, 0x00, 0x0A, 0x02, 0x01, 0x00, 0x2A, 0x06, 0x89, 0x95, 0xFC, 0xBE, 0x06,
             0x2A, 0x2B, 0x0E, 0x13, 0x43, 0x42, 0x01, 0x00, 0xD0, 0x0A, 0x02, 0xC6, 0x14, 0xA9, 0xF6,
             0xE2, 0xD3, 0xEF, 0xEA, 0xE6, 0xED, 0x01, 0x00, 0x00, 0x00, 0x00])
ON = bytes([0x43, 0x42, 0x01, 0x00, 0x0A, 0x02, 0x01, 0x00, 0x2A, 0x06, 0x89, 0x95, 0xFC, 0xBE, 0x06,
            0x2A, 0x2B, 0x0E, 0x15, 0x43, 0x42, 0x01, 0x00, 0x10, 0x00, 0xD0, 0x0A, 0x02, 0xC6, 0x14,
            0xA9, 0xF6, 0xE2, 0xD3, 0xEF, 0xEA, 0xE6, 0xED, 0x01, 0x00, 0x00, 0x00, 0x00])
TS = 1742670473
FT = 133_871_411_809_270_569


def test_parse_both_states():
    assert N.parse(OFF)[0] is False and N.parse(ON)[0] is True


def test_build_matches_windows_bytes():
    now = (FT / 10_000_000) - 11_644_473_600          # то же время, что в примере
    _on, body, tail = N.parse(OFF)
    got = N.build(True, body, tail, now=TS)
    assert got[:15] == ON[:15] and N.parse(got)[0] is True and len(got) == len(ON)
    _on, body, tail = N.parse(ON)
    back = N.build(False, body, tail, now=TS)
    assert N.parse(back)[0] is False and len(back) == len(OFF) and back[:15] == OFF[:15]
    assert abs(now - TS) < 10 ** 6


@pytest.mark.parametrize("bad", [b"", b"\x00" * 41, OFF[:20], ON.replace(b"\xd0\x0a", b"\xd0\x0b")])
def test_unknown_format_is_not_touched(bad):
    with pytest.raises((ValueError, IndexError)):
        N.parse(bad)
